"""
Result models for optimization output.
"""

from dataclasses import dataclass, field
from decimal import Decimal
from typing import Dict, List, Any, Optional, Union
from datetime import datetime

from dno_core.models.actions import (
    RelocationAction,
    FacilityConversionAction,
    ExpansionAction,
    RedesignAction,
    TestIntegrationAction,
    AddShiftAction,
)


# Type alias for any action
Action = Union[
    RelocationAction,
    FacilityConversionAction,
    ExpansionAction,
    RedesignAction,
    TestIntegrationAction,
    AddShiftAction,
]


@dataclass
class UtilizationReport:
    """
    Report of network utilization.
    
    Generated by UtilizationEvaluator to inform optimization decisions.
    """
    
    # Summary statistics
    total_labs: int = 0
    total_devices: int = 0
    total_capacity: int = 0
    total_demand: int = 0
    overall_utilization: float = 0.0
    
    # Categorized labs
    overutilized_labs: List[str] = field(default_factory=list)
    underutilized_labs: List[str] = field(default_factory=list)
    balanced_labs: List[str] = field(default_factory=list)
    
    # Per-lab details
    lab_utilizations: Dict[str, float] = field(default_factory=dict)
    lab_capacities: Dict[str, int] = field(default_factory=dict)
    lab_demands: Dict[str, int] = field(default_factory=dict)
    
    # Device-level details
    device_utilizations: Dict[str, float] = field(default_factory=dict)
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_labs": self.total_labs,
            "total_devices": self.total_devices,
            "total_capacity": self.total_capacity,
            "total_demand": self.total_demand,
            "overall_utilization": self.overall_utilization,
            "overutilized_count": len(self.overutilized_labs),
            "underutilized_count": len(self.underutilized_labs),
            "balanced_count": len(self.balanced_labs),
        }


@dataclass
class BandAnalysisResult:
    """
    Distance band analysis result.
    
    Shows population/facilities coverage by distance bands (e.g., 0-10km, 10-25km).
    """
    
    lab_id: str
    bands: List[Dict[str, Any]] = field(default_factory=list)
    total_population_covered: int = 0
    total_facilities_covered: int = 0
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "lab_id": self.lab_id,
            "bands": self.bands,
            "total_population_covered": self.total_population_covered,
            "total_facilities_covered": self.total_facilities_covered,
        }


@dataclass
class FinancialAxisScore:
    """
    Financial axis score for 3×3 matrix.
    
    Evaluates cost efficiency of the optimization.
    """
    
    # Currency
    currency: str = "INR"
    
    # Cost breakdown
    total_cost: Decimal = Decimal("0")
    testing_cost: Decimal = Decimal("0")
    # Annual sample logistics (optimized network); same as sample_transport_cost_optimized
    transport_cost: Decimal = Decimal("0")
    operational_cost: Decimal = Decimal("0")
    startup_cost: Decimal = Decimal("0")
    # Sample transport: baseline vs optimized annual route costs
    sample_transport_cost: Decimal = Decimal("0")
    sample_transport_cost_optimized: Decimal = Decimal("0")
    transport_cost_delta: Decimal = Decimal("0")
    transport_cost_delta_percent: float = 0.0
    # One-off CAPEX from relocations, expansions, conversions in this run
    capex_cost: Decimal = Decimal("0")
    
    # Comparison to baseline
    baseline_total_cost: Decimal = Decimal("0")
    cost_delta: Decimal = Decimal("0")
    cost_delta_percent: float = 0.0
    
    # Efficiency metrics
    cost_per_test: Decimal = Decimal("0")
    baseline_cost_per_test: Decimal = Decimal("0")
    
    # Overall score (0-100)
    score: float = 0.0
    description: str = "Cost efficiency: lower costs per test while maintaining quality"
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "currency": self.currency,
            "total_cost": float(self.total_cost),
            "cost_breakdown": {
                "testing": float(self.testing_cost),
                "transport": float(self.transport_cost),
                "sample_transport_baseline": float(self.sample_transport_cost),
                "sample_transport_optimized": float(self.sample_transport_cost_optimized),
                "sample_transport_delta": float(self.transport_cost_delta),
                "sample_transport_delta_percent": self.transport_cost_delta_percent,
                "capex": float(self.capex_cost),
                "operational": float(self.operational_cost),
                "startup": float(self.startup_cost),
            },
            "baseline_total_cost": float(self.baseline_total_cost),
            "cost_delta": float(self.cost_delta),
            "cost_delta_percent": self.cost_delta_percent,
            "score": self.score,
            "description": self.description,
        }


